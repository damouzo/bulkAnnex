def main():
    parser = argparse.ArgumentParser(
        description="Generate synthetic bulk RNA-seq demo data for bulkAnnex."
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="data_demo",
        help="Output directory for the counts TSV (default: data_demo/)",
    )
    parser.add_argument(
        "--seed", type=int, default=42, help="Random seed for reproducibility."
    )
    args = parser.parse_args()

    rng = np.random.default_rng(args.seed)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "salmon.merged.gene_counts.tsv"

    # Unpack gene panel
    gene_ids = [g[0] for g in GENE_PANEL]
    gene_names = [g[1] for g in GENE_PANEL]
    n_genes = len(gene_ids)
    logger.info(f"Gene panel: {n_genes} genes")

    # Sample definitions
    samples = [
        # (sample_name,   norm_group,   kd_effect, lib_factor_range, cell_line_b)
        ("CellLine_A_Scr_1", "CellLine_A", 0.0,  (0.92, 1.08), False),
        ("CellLine_A_Scr_2", "CellLine_A", 0.0,  (0.94, 1.06), False),
        ("CellLine_A_Scr_3", "CellLine_A", 0.0,  (0.96, 1.04), False),
        ("CellLine_A_KD_1",  "CellLine_A", 1.0,  (0.92, 1.08), False),
        ("CellLine_A_KD_2",  "CellLine_A", 1.0,  (0.94, 1.06), False),
        ("CellLine_A_KD_3",  "CellLine_A", 1.0,  (0.96, 1.04), False),
        ("CellLine_B_Scr_1", "CellLine_B", 0.0,  (0.92, 1.08), True),
        ("CellLine_B_Scr_2", "CellLine_B", 0.0,  (0.94, 1.06), True),
        ("CellLine_B_Scr_3", "CellLine_B", 0.0,  (0.96, 1.04), True),
        ("CellLine_B_KD_1",  "CellLine_B", 1.3,  (0.92, 1.08), True),  # stronger KD
        ("CellLine_B_KD_2",  "CellLine_B", 1.3,  (0.94, 1.06), True),
        ("CellLine_B_KD_3",  "CellLine_B", 1.3,  (0.96, 1.04), True),
    ]

    # Build per-gene baseline parameters (log-normal mean, gene-specific dispersion).
    # log-normal prior on mean gives realistic bulk RNA-seq count distributions:
    # most genes lowly expressed, few highly expressed.
    log_means = rng.normal(loc=3.5, scale=2.0, size=n_genes)  # log2 scale
    base_means = np.exp2(log_means)
    base_means = np.clip(base_means, 0.1, 50000)

    # Realistic dispersion: lower than default to ensure statistical power with 3 replicates.
    # Formula: overdispersion decreases as mean increases (inverse relationship).
    gene_dispersions = 0.15 + 0.3 / (base_means + 1.0)

    # Force high, consistent baseline expression for all KD scenario genes.
    # Without this, random log-normal sampling can give near-zero means
    # that DESeq2 cannot detect even with large fold changes.
    gene_name_idx = {g: i for i, g in enumerate(gene_names)}
    for gene in KD_TARGET_GENES:
        if gene in gene_name_idx:
            idx = gene_name_idx[gene]
            base_means[idx] = rng.uniform(150, 500)
            gene_dispersions[idx] = rng.uniform(0.04, 0.10)
    for gene in APOPTOSIS_UP_GENES + CELL_CYCLE_DOWN_GENES:
        if gene in gene_name_idx:
            idx = gene_name_idx[gene]
            base_means[idx] = rng.uniform(80, 300)
            gene_dispersions[idx] = rng.uniform(0.06, 0.14)

    # CellLine_B baseline: same starting point but with cell-line-specific shifts
    base_means_b = base_means.copy()
    for gene in CELL_LINE_B_UP_GENES:
        if gene in gene_name_idx:
            idx = gene_name_idx[gene]
            base_means_b[idx] = base_means_b[idx] * rng.uniform(1.5, 3.0)
    # Random per-gene shifts for ~30% of genes (realistic cell-line differences)
    n_shifted = int(0.30 * n_genes)
    shift_idx = rng.choice(n_genes, size=n_shifted, replace=False)
    base_means_b[shift_idx] *= rng.uniform(0.4, 2.5, size=n_shifted)
    base_means_b = np.clip(base_means_b, 0.1, 50000)

    logger.info(f"Generating counts for {len(samples)} samples...")

    # Generate counts matrix
    counts_matrix = {}
    for sample_name, norm_group, kd_effect, lib_range, is_cell_line_b in samples:
        lib_factor = rng.uniform(*lib_range)
        bm = base_means_b if is_cell_line_b else base_means
        sample_counts = generate_sample_counts(
            gene_names, bm.copy(), gene_dispersions.copy(),
            lib_factor, kd_effect, rng
        )
        sample_counts = add_salmon_decimals(sample_counts, rng)
        counts_matrix[sample_name] = sample_counts
        logger.info(
            f"  {sample_name}: library_factor={lib_factor:.3f}, "
            f"total_counts={sample_counts.sum():.0f}, "
            f"genes_detected={(sample_counts > 1).sum()}"
        )

    # Assemble TSV
    df = pd.DataFrame({"gene_id": gene_ids, "gene_name": gene_names})
    for sample_name, _ in [(s[0], s) for s in samples]:
        df[sample_name] = counts_matrix[sample_name]

    # Format floats to 3 decimal places (nf-core salmon style: 1325.999)
    float_cols = [s[0] for s in samples]
    for col in float_cols:
        df[col] = df[col].map(lambda x: f"{x:.3f}")

    df.to_csv(output_path, sep="\t", index=False)
    logger.info(f"Written: {output_path}  ({df.shape[0]} genes x {len(float_cols)} samples)")

    # Quick sanity check
    kd_cols = [s for s in float_cols if "_KD_" in s and "CellLine_A" in s]
    scr_cols = [s for s in float_cols if "_Scr_" in s and "CellLine_A" in s]
    if kd_cols and scr_cols:
        df_num = df.copy()
        for c in float_cols:
            df_num[c] = df_num[c].astype(float)
        gene_name_idx_local = {g: i for i, g in enumerate(gene_names)}
        kd_target_found = [g for g in KD_TARGET_GENES if g in gene_names]
        if kd_target_found:
            g = kd_target_found[0]
            kd_mean = df_num.loc[df_num["gene_name"] == g, kd_cols].values.astype(float).mean()
            scr_mean = df_num.loc[df_num["gene_name"] == g, scr_cols].values.astype(float).mean()
            fc = scr_mean / (kd_mean + 0.1)
            logger.info(f"Sanity check — {g}: Scr mean={scr_mean:.1f}, KD mean={kd_mean:.1f}, fold-down={fc:.1f}x")


if __name__ == "__main__":
    main()
