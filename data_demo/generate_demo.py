def neg_binom_counts(mean: float, dispersion: float, n: int, rng) -> np.ndarray:
    """
    Sample n counts from a negative binomial parameterised by mean and dispersion.
    dispersion = 1/r (variance = mean + mean^2 * dispersion).
    """
    if mean <= 0:
        return np.zeros(n, dtype=np.float32)
    r = max(1.0 / dispersion, 1e-3)
    p = r / (r + mean)
    return rng.negative_binomial(r, p, size=n).astype(np.float32)


